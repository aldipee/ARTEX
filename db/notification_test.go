func TestClaimRealtimeDeliveriesHonorsLeaseAndMode(t *testing.T) {
	d := notifyTestDB(t)
	ctx := context.Background()

	realtime := newTestChannel(t, d, notify.KindDingTalk, NotifyModeRealtime, `{}`)
	digest := newTestChannel(t, d, notify.KindDingTalk, NotifyModeDigest, `{}`)

	addTestEvent(t, d, notify.EventFindingCreated, 3001, notify.Snapshot{Severity: "high", VulnClass: "XSS"})
	if _, _, err := d.FanOutPendingEvents(ctx, 100); err != nil {
		t.Fatal(err)
	}

	// Realtime claiming should return only the realtime channel's delivery, not the digest channel's.
	got, err := d.ClaimRealtimeDeliveries(ctx, realtime.ID, 10, time.Minute)
	if err != nil {
		t.Fatalf("claim failed: %v", err)
	}
	if len(got) != 1 {
		t.Fatalf("expected to claim one delivery; got %d", len(got))
	}
	if got[0].State != NotifyStateSending || got[0].Attempts != 1 {
		t.Fatalf("after claiming, state should be sending and attempts=1; got state=%s attempts=%d", got[0].State, got[0].Attempts)
	}
	// The joined rendering context must include channel config, event snapshot, and finding ID.
	if got[0].Channel == nil || len(got[0].Channel.Config) == 0 {
		t.Fatal("claimed delivery is missing channel config, so rendering would fail")
	}
	if got[0].FindingID != 3001 {
		t.Fatalf("finding ID was not copied from the event; got %d", got[0].FindingID)
	}

	// A second claim should be empty while the lease is active, preventing two dispatchers from sending the same row.
	again, err := d.ClaimRealtimeDeliveries(ctx, realtime.ID, 10, time.Minute)
	if err != nil {
		t.Fatal(err)
	}
	if len(again) != 0 {
		t.Fatalf("should not reclaim a delivery while its lease is active; got %d", len(again))
	}

	// A realtime claim must not return a digest-channel delivery.
	left, err := d.ClaimRealtimeDeliveries(ctx, digest.ID, 10, time.Minute)
	if err != nil {
		t.Fatal(err)
	}
	if len(left) != 0 {
		t.Fatalf("realtime claim should not return a digest-channel delivery; got %d", len(left))
	}
}

